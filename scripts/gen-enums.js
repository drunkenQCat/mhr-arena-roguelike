// SDK 自动生成 Stage 1：枚举。
// 解析 REFramework 自动导出的 <game>/Enums_Internal.hpp（RTTI 枚举全量 dump），
// 按命名空间前缀筛选后生成 src/game/gen/enums/ 下一枚举一文件
// （const 对象 + keyof 类型）。TSTL 按 require 粒度打包：只 import 用到的枚举才进 bundle。
// 游戏已停更（16.0.2.0 / build 17920865），一次 dump 永久有效；换版本重跑本脚本即可。
//
// 用法：node scripts/gen-enums.js
//   生成范围 = 引用闭环：源码里 import 的（gen/enums/<名字>）∪ data/gen_allowlist.txt 列名的。
//   需要新枚举时：源码加一行 import，或把名字写进 allowlist，重新 build 即可。
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const { findGameDir } = require("./game-dir");

const root = path.resolve(__dirname, "..");
const OUT_DIR = path.join(root, "src", "game", "gen", "enums");

// 真源优先级：仓库快照 sdk-dump/ > 游戏目录（换游戏版本时重拷快照并重跑本脚本）
const localDump = path.join(root, "sdk-dump", "Enums_Internal.hpp");
const hppPath = fs.existsSync(localDump) ? localDump : path.join(findGameDir(), "Enums_Internal.hpp");
if (!fs.existsSync(hppPath)) {
  console.error(`FAIL 枚举 dump 不存在：${hppPath}（仓库 sdk-dump/ 或游戏目录 reframework dump）`);
  process.exit(1);
}
const src = fs.readFileSync(hppPath, "utf8");

// 引用闭环：只生成 被源码 import 的 + data/gen_allowlist.txt 列名的枚举。
// 原因：TSTL luaBundle 会打包编译集内全部文件，全量生成会把 800KB 枚举塞进 bundle。
const allowFile = path.join(root, "data", "gen_allowlist.txt");
const wanted = new Set();
for (const f of fs.readdirSync(path.join(root, "src")).flatMap((d) => walkTs(path.join(root, "src", d)))) {
  for (const m of f.content.matchAll(/gen\/enums\/(\w+)/g)) wanted.add(m[1]);
}
if (fs.existsSync(allowFile)) {
  for (const line of fs.readFileSync(allowFile, "utf8").split(/\r?\n/)) {
    const raw = line.replace(/\/\/.*$/, "").trim();
    if (raw) wanted.add(raw.replace(/[.:]/g, "_")); // 点分原名或 flat 名统一 flat 化
  }
}
function walkTs(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walkTs(p));
    else if (e.name.endsWith(".ts")) out.push({ content: fs.readFileSync(p, "utf8") });
  }
  return out;
}

// 解析 "namespace a::b::C { enum E { ... } }"，体{}内不允许嵌套（dump 格式保证）
const enumRe = /namespace ([\w:]+) \{\s*\r?\n\s*enum (\w+) \{([^}]+?)\}/g;
const merged = new Map(); // flatName -> { ns, enumName, entries: Map<string, number> }
let total = 0;

let m;
while ((m = enumRe.exec(src)) !== null) {
  const [, ns, enumName, body] = m;
  total++;
  const flat0 = (ns + "_" + enumName).replace(/::/g, "_");
  if (!wanted.has(flat0)) continue; // 引用闭环：没被 import 也没进 allowlist 的一律不生成

  const entries = new Map();
  let implicit = 0;
  for (let line of body.split(/\r?\n/)) {
    line = line.replace(/\/\/.*$/, "").trim().replace(/,$/, "").trim();
    if (line === "") continue;
    const assign = line.match(/^(\w+)\s*=\s*(-?(?:0x[0-9a-fA-F]+|\d+))$/);
    if (assign) {
      entries.set(assign[1], Number(assign[2]));
      implicit = Number(assign[2]) + 1;
    } else if (/^\w+$/.test(line)) {
      entries.set(line, implicit++); // 隐式递增枚举项
    }
    // 表达式值等罕见形态：跳过
  }

  const flat = (ns + "_" + enumName).replace(/::/g, "_");
  const slot = merged.get(flat) ?? { ns, enumName, entries: new Map() };
  for (const [k, v] of entries) slot.entries.set(k, v); // 重名声明合并，后到覆盖
  if (!merged.has(flat)) merged.set(flat, slot);
}

// 生成 TS。命名保证合法标识符；值全为 number。
fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
let conflicts = 0;
for (const [flat, { ns, enumName, entries }] of merged) {
  const seen = new Map();
  for (const [k, v] of entries) {
    if (seen.has(k) && seen.get(k) !== v) conflicts++;
    seen.set(k, v);
  }
  const body = [...seen.entries()].map(([k, v]) => `  ${k}: ${v},`).join("\n");
  const content = [
    "// GENERATED by scripts/gen-enums.js from REFramework Enums_Internal.hpp — do not edit.",
    `/** ${ns}::${enumName} */`,
    `export const ${flat} = {`,
    body,
    "} as const;",
    `export type ${flat} = keyof typeof ${flat};`,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(OUT_DIR, `${flat}.ts`), content);
}

console.log(`GEN ${OUT_DIR}: ${merged.size} enums kept of ${total} scanned` +
  (conflicts ? `; ${conflicts} conflicting duplicate entries resolved last-wins` : ""));
