// SDK 自动生成 Stage 2：类型接口。
// 读 sdk-dump/sdk_types.json（sdk_type_probe.lua 的运行时探测产物），
// 每个 snow.* 类型生成 src/game/gen/types/<Flat>.ts：
//   interface <Flat> { get_field(name: "<字段名>"): <精确类型>; call(name: "<方法名>", ...): <返回>; ... }
// 纯类型零运行时（不进 bundle）；字段名拼错/类型错用会在 tsc 编译期报错，
// 取代手写的 `as number` 断言链。基元外的未知类型一律 REManagedObject。
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const DUMP = path.join(root, "sdk-dump", "sdk_types.json");
const OUT_DIR = path.join(root, "src", "game", "gen", "types");
const MAX_OVERLOADS = 6;
const SKIP_METHODS = new Set([".ctor", "Finalize"]);

const PRIMITIVES = {
  "System.Boolean": "boolean",
  "System.Byte": "number",
  "System.SByte": "number",
  "System.Int16": "number",
  "System.UInt16": "number",
  "System.Int32": "number",
  "System.UInt32": "number",
  "System.Int64": "number",
  "System.UInt64": "number",
  "System.Single": "number",
  "System.Double": "number",
  "System.String": "string",
  "System.Char": "string",
};

function flatName(full) {
  return full.replace(/::/g, "_").replace(/\./g, "_");
}

/** REEngine 类型全名 → TS 类型表达式。knownTypes=dump 类型集合；knownEnums=Stage1 枚举集合。 */
function mapType(full, knownTypes, knownEnums) {
  if (!full || full === "System.Void") return "void";
  if (PRIMITIVES[full]) return PRIMITIVES[full];
  if (/[\[\],&<>]/.test(full)) return "REManagedObject"; // 数组/多维数组/泛型容器/引用参数
  if (knownEnums && knownEnums.has(flatName(full))) return "number"; // 枚举用 Stage1 数字常量
  if (knownTypes.has(full)) return flatName(full);
  return "REManagedObject";
}

/** 生成全部类型接口：{ files: [{name, content}] }。content 无 import 头（finalize 补）。 */
function generateTypes(dump, knownEnums = new Set()) {
  const known = new Set(Object.keys(dump.types));
  for (const e of knownEnums) known.delete(e); // 枚举不生成 interface
  const files = [];
  for (const [full, t] of Object.entries(dump.types)) {
    if (!/^[\w.]+$/.test(full)) continue; // 泛型实例化（BitSetFlag`1<...> 等）不做文件名/标识符；字段映射兜底 REManagedObject
    const flat = flatName(full);
    const lines = [`export interface ${flat} extends REManagedObject {`];

    // ---- get_field：按精确字段名重载，末尾 string 兜底返回 unknown ----
    const fieldNames = new Set();
    for (const f of t.fields || []) {
      if (f.static || fieldNames.has(f.name)) continue;
      fieldNames.add(f.name);
      lines.push(`  /** offset=${f.offset} type=${f.type} */`);
      lines.push(`  get_field(name: ${JSON.stringify(f.name)}): ${mapType(f.type, known, knownEnums)};`);
    }
    lines.push(`  get_field(name: string): unknown;`);

    // ---- set_field：下划线可写字段生成精确重载 ----
    for (const f of t.fields || []) {
      if (f.static || !f.name.startsWith("_")) continue;
      const tsType = mapType(f.type, known, knownEnums);
      if (tsType === "unknown") continue;
      lines.push(`  set_field(name: ${JSON.stringify(f.name)}, value: ${tsType}): void;`);
    }
    lines.push(`  set_field(name: string, value: unknown): void;`);

    // ---- call：同名方法取首个签名（dump 侧已按名合并，overloads 计数保留在注释）----
    const seenNames = new Set();
    for (const meth of t.methods || []) {
      if (SKIP_METHODS.has(meth.name) || seenNames.has(meth.name)) continue;
      seenNames.add(meth.name);
      const params = (meth.params || []).map((p, i) => `arg${i}: ${mapType(p.type, known, knownEnums)}`).join(", ");
      const multi = (meth.overloads || 1) > 1 ? `（共 ${meth.overloads} 个重载，取首个）` : "";
      lines.push(`  /** -> ${meth.ret}${multi} */`);
      lines.push(`  call(name: ${JSON.stringify(meth.name)}${params ? ", " + params : ""}): ${mapType(meth.ret, known, knownEnums)};`);
    }
    lines.push(`  call(name: string, ...args: unknown[]): unknown;`);
    lines.push(`}`);

    const content = [
      "// GENERATED by scripts/gen-types.js from sdk-dump/sdk_types.json — do not edit.",
      `/** ${full}：${(t.fields || []).length} fields / ${(t.methods || []).length} method names */`,
      lines.join("\n"),
      "",
    ].join("\n");
    files.push({ name: `${flat}.ts`, content, flat });
  }
  return { files };
}

/** 补 import 头：内容里引用了哪些生成类型/REManagedObject（用 \bsnow_ 边界匹配 flat 标识符）。 */
function finalize(content, selfFlat) {
  const header = [];
  const refs = new Set(content.match(/\bsnow_[A-Za-z0-9_]*\b/g) || []);
  refs.delete(selfFlat);
  for (const ref of refs) header.push(`import type { ${ref} } from "./${ref}";`);
  if (/\bREManagedObject\b/.test(content)) header.unshift(`import type { REManagedObject } from "../../sdk";`);
  return [...header, content].join("\n");
}

module.exports = { generateTypes, finalize, mapType, flatName };

if (require.main === module) {
  if (!fs.existsSync(DUMP)) {
    console.error(`FAIL 类型 dump 不存在：${DUMP}（先部署 sdk_type_probe.lua 跑一次游戏收割）`);
    process.exit(1);
  }
  const dump = JSON.parse(fs.readFileSync(DUMP, "utf8"));
  const enumsDir = path.join(root, "src", "game", "gen", "enums");
  const knownEnums = new Set(
    fs.existsSync(enumsDir) ? fs.readdirSync(enumsDir).map((f) => f.replace(/\.ts$/, "")) : [],
  );
  const { files } = generateTypes(dump, knownEnums);
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const f of files) {
    fs.writeFileSync(path.join(OUT_DIR, f.name), finalize(f.content, f.flat));
  }
  console.log(`GEN ${OUT_DIR}: ${files.length} type interfaces`);
}
