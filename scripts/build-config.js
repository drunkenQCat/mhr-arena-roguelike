// 构建脚本：把 data/rogue_config.json 内嵌为 src/game/default_config.ts
// （TSTL 对 JSON 导入支持不佳，生成 TS 常量最稳）。产物 gitignore 排除。
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const raw = fs.readFileSync(path.join(root, "data", "rogue_config.json"), "utf8");
// 去注释（JSONC 兼容）：逐行剥离 // 注释（字符串内的 // 不存在于此文件，够用）
const stripped = raw
  .split(/\r?\n/)
  .filter((line) => !line.trim().startsWith("//"))
  .join("\n");
const cfg = JSON.parse(stripped);
const monsters = JSON.parse(fs.readFileSync(path.join(root, "data", "monster_ids.json"), "utf8"));
const out = "// GENERATED by scripts/build-config.js — do not edit.\n" +
  `export const defaultConfig = ${JSON.stringify(cfg, null, 2)};\n` +
  `export const monsterCatalog = ${JSON.stringify(monsters, null, 2)};\n`;
fs.writeFileSync(path.join(root, "src", "game", "default_config.ts"), out);
console.log("default_config.ts generated");
